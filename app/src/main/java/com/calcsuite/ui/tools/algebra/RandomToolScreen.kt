import java.math.BigDecimal

private enum class GeneratorMode { Integer, Decimal }

@Composable
fun RandomToolScreen(args: ToolArgs) {
    val fmt = rememberFmt()
    val copy = rememberCopyAction()

    var modeName by rememberSaveable { mutableStateOf(GeneratorMode.Integer.name) }
    val mode = GeneratorMode.valueOf(modeName)
    var minText by rememberSaveable { mutableStateOf("1") }
    var maxText by rememberSaveable { mutableStateOf("100") }
    var countText by rememberSaveable { mutableStateOf("10") }
    var decimalPlacesText by rememberSaveable { mutableStateOf("2") }
    var unique by rememberSaveable { mutableStateOf(false) }
    var parityName by rememberSaveable { mutableStateOf(RandomParity.Any.name) }
    var seedText by rememberSaveable { mutableStateOf("") }
    var secure by rememberSaveable { mutableStateOf(false) }

    var generated by remember { mutableStateOf<List<String>>(emptyList()) }
    var generatedNotes by remember { mutableStateOf<List<String>>(emptyList()) }
    var generatedError by remember { mutableStateOf<String?>(null) }
    var generatedSummary by remember { mutableStateOf<List<Pair<String, String>>>(emptyList()) }
    var lastAction by remember { mutableStateOf("") }

    fun num(v: BigDecimal) = fmt.num(v, precision = maxOf(fmt.precision, 10))

    fun <T> applyResult(
        result: CalcResult<com.calcsuite.engine.algebra.GenerationResult<T>>,
        format: (T) -> String,
        summary: (List<T>) -> List<Pair<String, String>>,
    ) {
        when (result) {
            is CalcResult.Err -> {
                generated = emptyList()
                generatedSummary = emptyList()
                generatedNotes = emptyList()
                generatedError = result.error.message
            }
            is CalcResult.Ok -> {
                val value = result.value
                generated = value.values.map(format)
                generatedSummary = summary(value.values)
                generatedNotes = value.notes
                generatedError = null
                lastAction = when (mode) {
                    GeneratorMode.Integer ->
                        "${value.values.size} integer(s) in [$minText, $maxText]" +
                            (if (unique) ", unique" else "") +
                            (if (parityName != RandomParity.Any.name) ", ${parityName.lowercase()}" else "")
                    GeneratorMode.Decimal ->
                        "${value.values.size} decimal(s) in [$minText, $maxText] with $decimalPlacesText decimal place(s)"
                }
            }
        }
    }

    fun generate() {
        val count = Num.parseIntOrNull(countText)?.toInt()
        val seed = seedText.trim().takeIf { it.isNotEmpty() }?.toLongOrNull()
        val seedError = seedText.trim().isNotEmpty() && seed == null
        when {
            count == null || count < 1 -> {
                generated = emptyList()
                generatedSummary = emptyList()
                generatedNotes = emptyList()
                generatedError = "Enter a whole count of at least 1"
                return
            }
            count > RandomEngine.MAX_COUNT -> {
                generated = emptyList()
                generatedSummary = emptyList()
                generatedNotes = emptyList()
                generatedError = "At most ${RandomEngine.MAX_COUNT} values can be generated at once"
                return
            }
            seedError -> {
                generated = emptyList()
                generatedSummary = emptyList()
                generatedNotes = emptyList()
                generatedError = "The seed must be a whole number"
                return
            }
        }
        if (mode == GeneratorMode.Integer) {
            val min = Num.parseIntOrNull(minText)
            val max = Num.parseIntOrNull(maxText)
            if (min == null || max == null) {
                generated = emptyList()
                generatedSummary = emptyList()
                generatedNotes = emptyList()
                generatedError = "Enter whole numbers for the minimum and maximum"
                return
            }
            val result = RandomEngine.generateIntegers(
                IntegerGeneratorConfig(
                    min = min,
                    max = max,
                    count = count,
                    unique = unique,
                    parity = RandomParity.valueOf(parityName),
                    seed = seed,
                    useSecureRandom = secure,
                ),
            )
            applyResult(
                result = result,
                format = { it.toString() },
                summary = { values ->
                    listOf(
                        "Count" to values.size.toString(),
                        "Smallest" to values.minOrNull().toString(),
                        "Largest" to values.maxOrNull().toString(),
                        "Sum" to values.fold(java.math.BigInteger.ZERO) { acc, v -> acc.add(v) }.toString(),
                        "Distinct" to values.distinct().size.toString(),
                    )
                },
            )
        } else {
            val min = Num.parseOrNull(minText)
            val max = Num.parseOrNull(maxText)
            val places = Num.parseIntOrNull(decimalPlacesText)?.toInt()
            if (min == null || max == null) {
                generated = emptyList()
                generatedSummary = emptyList()
                generatedNotes = emptyList()
                generatedError = "Enter valid numbers for the minimum and maximum"
                return
            }
            if (places == null || places < 0 || places > 12) {
                generated = emptyList()
                generatedSummary = emptyList()
                generatedNotes = emptyList()
                generatedError = "Decimal places must be between 0 and 12"
                return
            }
            val result = RandomEngine.generateDecimals(
                DecimalConfig(
                    min = min,
                    max = max,
                    count = count,
                    decimalPlaces = places,
                    seed = seed,
                    useSecureRandom = secure,
                ),
            )
            applyResult(
                result = result,
                format = { fmt.num(it, precision = maxOf(fmt.precision, places + 1)) },
                summary = { values ->
                    listOf(
                        "Count" to values.size.toString(),
                        "Smallest" to num(values.minOrNull() ?: BigDecimal.ZERO),
                        "Largest" to num(values.maxOrNull() ?: BigDecimal.ZERO),
                        "Sum" to num(values.fold(BigDecimal.ZERO) { acc, v -> acc.add(v) }),
                        "Distinct" to values.distinct().size.toString(),
                    )
                },
            )
        }
    }

    ToolScaffold(
        title = args.tool.title,
        subtitle = args.tool.description,
        onBack = args.onBack,
        favorite = args.favorite,
        onToggleFavorite = args.onToggleFavorite,
        actions = {
            TextButton(onClick = {
                minText = "1"; maxText = "100"; countText = "10"; decimalPlacesText = "2"
                unique = false; parityName = RandomParity.Any.name; seedText = ""; secure = false
                generated = emptyList(); generatedNotes = emptyList(); generatedError = null
                generatedSummary = emptyList()
            }) { Text("Reset") }
        },
    ) {
        SegmentedChoice(
            options = listOf(
                GeneratorMode.Integer.name to "Integers",
                GeneratorMode.Decimal.name to "Decimals",
            ),
            selected = modeName,
            onSelect = {
                modeName = it
                generated = emptyList(); generatedNotes = emptyList(); generatedError = null
                generatedSummary = emptyList()
            },
            label = "Mode",
        )

        Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
            NumberField("Minimum (inclusive)", minText, { minText = it }, error = if (Num.parseOrNull(minText) == null) "Enter a valid number" else null)
            NumberField("Maximum (inclusive)", maxText, { maxText = it }, error = if (Num.parseOrNull(maxText) == null) "Enter a valid number" else null)
            NumberField("How many", countText, { countText = it }, integerOnly = true, error = if (Num.parseIntOrNull(countText) == null) "Enter a whole number" else null)
            if (mode == GeneratorMode.Decimal) {
                NumberField(
                    label = "Decimal places",
                    value = decimalPlacesText,
                    onValueChange = { decimalPlacesText = it },
                    integerOnly = true,
                    error = if (Num.parseIntOrNull(decimalPlacesText) == null) "Enter a whole number" else null,
                )
            }
        }

        if (mode == GeneratorMode.Integer) {
            SegmentedChoice(
                options = RandomParity.entries.map { it.name to it.name },
                selected = parityName,
                onSelect = { parityName = it },
                label = "Parity",
            )
        }

        ExpandablePanel(title = "Generation options") {
            if (mode == GeneratorMode.Integer) {
                ToggleRow(
                    label = "Unique values",
                    checked = unique,
                    onCheckedChange = { unique = it },
                    description = "Every value appears at most once (a range must be large enough)",
                )
            }
            NumberField(
                label = "Seed (optional)",
                value = seedText,
                onValueChange = { seedText = it },
                placeholder = "e.g. 42",
                error = if (seedText.trim().isNotEmpty() && seedText.trim().toLongOrNull() == null) "Enter a whole number" else null,
            )
            ToggleRow(
                label = "Cryptographically secure",
                checked = secure,
                onCheckedChange = { secure = it },
                description = "Use java.security.SecureRandom instead of java.util.Random; the seed is ignored",
            )
        }

        Button(
            onClick = { generate() },
            modifier = Modifier.fillMaxWidth(),
        ) {
            Text("Generate")
        }

        ResultCard(
            label = if (generated.isEmpty()) "Generated values" else "Generated ${generated.size} value(s)",
            value = when {
                generated.isEmpty() -> null
                generated.size <= 6 -> generated.joinToString(", ")
                else -> generated.take(6).joinToString(", ") + " …"
            },
            caption = if (generated.isEmpty()) null else {
                if (secure) "Secure randomness (java.security.SecureRandom)"
                else if (seedText.trim().isNotEmpty()) "Seeded with ${seedText.trim()} — reproducible"
                else "java.util.Random — not cryptographically secure"
            },
            error = generatedError,
            onCopy = { copy(it, "Generated values") },
            copyValue = generated.joinToString(", "),
            onSave = if (generated.isEmpty()) null else {
                { args.onRecord(lastAction, generated.joinToString(", ").take(400)) }
            },
        )

        if (generated.isNotEmpty()) {
            SectionCard(title = "All values") {
                SelectionContainer {
                    Text(
                        generated.joinToString(", "),
                        style = MaterialTheme.typography.bodyMedium,
                        modifier = Modifier
                            .fillMaxWidth()
                            .heightIn(max = 220.dp)
                            .verticalScroll(rememberScrollState()),
                    )
                }
            }
            Column(Modifier.fillMaxWidth()) {
                generatedSummary.forEach { (label, value) -> ResultRow(label, value) }
            }
            Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                Button(onClick = { generate() }) { Text("Regenerate") }
                TextButton(onClick = { copy(generated.joinToString(", "), "Generated values") }) {
                    Text("Copy all")
                }
            }
        }

        generatedNotes.forEach { InfoNote(it) }

        FormulaCard(
            formula = "value ⊆ [min, max], both endpoints inclusive",
            explanation = "Integers are drawn uniformly from the (optionally parity-filtered) range; decimals are drawn " +
                "uniformly from the grid of the chosen number of decimal places.",
            variables = listOf(
                "seed" to "reproduces the same list for java.util.Random",
                "secure" to "java.security.SecureRandom, suitable for secrets",
            ),
        )
    }
}
